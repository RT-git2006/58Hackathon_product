const RE_ASCII_WORD = /^[a-z][a-z' ]*$/;
const asciiRegex = new Map();
// text に単語 w が含まれるか。英単語は小文字にした text の中で、前後が英字でない位置だけ一致させる
function hasWord(text, lower, w) {
  if (!RE_ASCII_WORD.test(w)) return text.includes(w);
  let re = asciiRegex.get(w);
  if (!re) asciiRegex.set(w, (re = new RegExp(`(^|[^a-z])${w}([^a-z]|$)`)));
  return re.test(lower);
}

const RE_KATAKANA = /^[゠-ヿー・！？!?]+$/;
// ドキドキ・ゴゴゴ・わくわく のような繰り返しの擬音
const RE_SOUND = /^([ぁ-ヿ]{1,3})\1+[っッーぁ-ぉァ-ォ！!]*$/;
const RE_NUMBER = /[0-9０-９]/;

const classifyCache = new Map();

function classifyChunk(text) {
  if (classifyCache.has(text)) return classifyCache.get(text);
  const score = {};
  const add = (cat, v) => (score[cat] = (score[cat] || 0) + v);
  const lower = text.toLowerCase();
  // 一致した言葉を長い順に見て、もっと長く一致した言葉の中にある短い言葉は数えない（「スクール」の中の「クール」など）
  const hits = [];
  for (const [w, cat] of WORD_LIST) {
    if (RE_ASCII_WORD.test(w)) {
      if (hasWord(text, lower, w)) add(cat, 2 + w.length);
      continue;
    }
    const i = text.indexOf(w);
    if (i >= 0) hits.push([i, w.length, cat]);
  }
  hits.sort((a, b) => b[1] - a[1]);
  const taken = [];
  for (const [i, len, cat] of hits) {
    if (taken.some(([j, l]) => len < l && i >= j && i + len <= j + l)) continue;
    taken.push([i, len]);
    add(cat, 2 + len);
  }
  for (const ch of text) {
    const cat = KANJI_MAP.get(ch);
    if (cat) add(cat, 1.5);
  }
  if (RE_SOUND.test(text)) add('sound', 3);
  // 付く絵文字の分類からも推定する（CLDR の約 4000 語。辞書に無い単語でも、絵文字があれば内容と雰囲気が分かる）
  const e = findEmoji(text);
  const ec = e && typeof CLDR_EMOJI_CAT !== 'undefined' && CLDR_EMOJI_CAT[e.replace(/️/g, '')];
  if (ec) add(ec, 2.5);

  let best = null;
  let bestScore = 0;
  for (const [cat, v] of Object.entries(score)) {
    if (v > bestScore) {
      best = cat;
      bestScore = v;
    }
  }
  if (!best) {
    if (RE_NUMBER.test(text)) best = 'tech';
    else if (text.length >= 2 && RE_KATAKANA.test(text)) best = 'katakana';
    else best = 'neutral';
  }
  classifyCache.set(text, best);
  return best;
}

