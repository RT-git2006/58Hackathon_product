// CLDR（Unicode 公式の日本語キーワード）の表。どんな単語でも、あれば絵文字を付ける
const CLDR_MAP = new Map(typeof CLDR_EMOJI_JA === 'undefined' ? [] : Object.entries(CLDR_EMOJI_JA));
const RE_KANJI_STEM = /^([一-鿿])[ぁ-ゟ]*$/;

function findEmojiCldr(text) {
  // 長い単語から順に、単語の中に含まれる言葉を探す
  const n = text.length;
  for (let len = Math.min(n, 10); len >= 2; len--) {
    for (let i = 0; i + len <= n; i++) {
      const e = CLDR_MAP.get(text.slice(i, i + len));
      if (e) return { e, len };
    }
  }
  // 1 文字の漢字は、その漢字が単語の中心のとき（後ろが送り仮名・助詞だけ）に限る（「火曜」で🔥にしない）
  const m = text.match(RE_KANJI_STEM);
  const e = m && CLDR_MAP.get(m[1]);
  return e ? { e, len: 1 } : { e: '', len: 0 };
}

const emojiCache = new Map();

function findEmoji(text) {
  if (emojiCache.has(text)) return emojiCache.get(text);
  // 手書きの辞書と CLDR の両方で探し、長く一致した方を使う（「神社」は「神」ではなく⛩）
  let found = '';
  let foundLen = 0;
  const lower = text.toLowerCase();
  for (const [w, e] of EMOJI_LIST) {
    if (hasWord(text, lower, w)) {
      found = e;
      foundLen = w.length;
      break;
    }
  }
  const c = findEmojiCldr(text);
  if (c.e && c.len > foundLen) found = c.e;
  emojiCache.set(text, found);
  return found;
}

